"""Generate ``resources/*.yml`` (jobs + variables) from ``XML/*`` and ``biis_lakehouse.ops.tasks``.

    cd databricks && python resources/generate.py          # rewrite
    cd databricks && python resources/generate.py --check  # exit 1 if the committed YAML is stale

The XML is the source of truth for task order, workflow-variable propagation, parameters and notification lists;
``tests/test_bundle.py`` re-checks the committed YAML against the XML independently.
"""
from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
BUNDLE_ROOT = HERE.parent
REPO_ROOT = BUNDLE_ROOT.parent
XML_DIR = REPO_ROOT / "XML"
sys.path.insert(0, str(BUNDLE_ROOT / "src"))

from biis_lakehouse.ops.tasks import EMAIL_TASKS, SESSION_COMMANDS  # noqa: E402

HEADER = "# GENERATED by resources/generate.py from XML/* - do not edit by hand.\n"
PARAM_RE = re.compile(r"\$(?:Param_|\$WF_)\w+")
EHRP_WF = "wf_EHRP2BIIS_UPDATE"
PARAMIKO = "paramiko>=3.4,<4"  # ops SFTP; the wheel itself has no runtime dependencies

# PLAN.md section 4.1: workflow -> workflows it waits for in biis_pay_period (writer -> reader edges).
PAY_PERIOD_DEPENDS = {
    "wf_Pay_Calendar": [],
    "wf_Pseudossn": ["wf_Pay_Calendar"],
    "wf_COMPTIME": ["wf_Pay_Calendar"],
    "wf_CPM": ["wf_Pseudossn"],
    "wf_LES": ["wf_Pseudossn"],
    "wf_CPM_AFPS": ["wf_CPM"],
    "wf_CPM_CDC": ["wf_CPM"],
    "wf_CPM_NIH": ["wf_CPM"],
    "wf_CPM_OIG": ["wf_CPM"],
    "wf_FDA_Leave": ["wf_CPM_AFPS"],
}

# Bundle variables for the ops tasks (not PowerCenter parameters).
OPS_PARAMS = ["SFTP_HOST", "SFTP_PORT", "SFTP_USER", "SFTP_KEY_HAS_PASSPHRASE", "SECRET_SCOPE", "SMTP_HOST",
              "SMTP_PORT", "SMTP_SENDER", "SMTP_USER", "TRANSFER_EMAIL_LIST", "FAIL_TASK_ON_COMMAND_ERROR"]


def var_name(param: str) -> str:
    """``$Param_CPM_PAD_filename`` -> ``CPM_PAD_filename``, ``$$WF_PP_NUM`` -> ``WF_PP_NUM`` (PLAN.md section 5)."""
    return param.removeprefix("$$").removeprefix("$Param_")


@dataclass
class Workflow:
    name: str
    chain: list[tuple[str, str]]  # (task instance name, TASKTYPE) in WORKFLOWLINK order, Start excluded
    params: list[str]  # $Param_* / $$WF_* referenced anywhere in the export, sorted
    var_setters: set[str] = field(default_factory=set)  # sessions with $$WF_* post-session success assignments
    failure_list: str | None = None  # session on-failure email recipient (a $$WF_* list or a literal)
    success_list: str | None = None  # only for sessions whose success email is not reproduced by an ops task
    schedule: dict = field(default_factory=dict)


def parse_workflow(path: Path) -> Workflow:
    root = ET.parse(path).getroot()
    (wf,) = root.iter("WORKFLOW")
    types = {t.get("NAME"): t.get("TASKTYPE") for t in wf.iter("TASKINSTANCE")}
    links = {}
    for link in wf.iter("WORKFLOWLINK"):
        if link.get("FROMTASK") in links:
            raise ValueError(f"{wf.get('NAME')}: branching at {link.get('FROMTASK')} is not supported")
        links[link.get("FROMTASK")] = link.get("TOTASK")
    start = next(n for n, t in types.items() if t == "Start")
    chain, cur = [], start
    while cur in links:
        cur = links[cur]
        chain.append((cur, types[cur]))

    out = Workflow(wf.get("NAME"), chain, sorted(set(PARAM_RE.findall(path.read_text(encoding="utf-8", errors="replace")))))
    sessions = {s.get("NAME"): s for s in root.iter("SESSION")}
    instance_to_session = {t.get("NAME"): t.get("TASKNAME") for t in wf.iter("TASKINSTANCE")}
    for inst, ttype in chain:
        if ttype != "Session":
            continue
        sess = sessions[instance_to_session[inst]]
        for comp in sess.iter("SESSIONCOMPONENT"):
            kind = comp.get("REFOBJECTNAME")
            if kind == "postsession_success_variable_assignment":
                if any(vp.get("NAME", "").startswith("$$WF_") for vp in comp.iter("VALUEPAIR")):
                    out.var_setters.add(inst)
            elif kind in ("on_failure_mail", "on_success_mail"):
                attrs = {a.get("NAME"): a.get("VALUE") for a in comp.iter("ATTRIBUTE")}
                if attrs.get("Email User Name"):
                    setattr(out, "failure_list" if kind == "on_failure_mail" else "success_list",
                            getattr(out, "failure_list" if kind == "on_failure_mail" else "success_list")
                            or attrs["Email User Name"])
    sched = next(wf.iter("SCHEDULEINFO"), None)
    if sched is not None:
        out.schedule = dict(sched.attrib)
        for el in sched.iter():
            out.schedule.update(el.attrib)
    return out


def load_workflows() -> dict[str, Workflow]:
    wfs = {}
    for path in sorted(XML_DIR.iterdir()):
        if path.is_file():
            wf = parse_workflow(path)
            wfs[wf.name] = wf
    return wfs


def _wheel_task(key: str, workflow: str, task: str, params: list[str], upstream: list[str], deps: list[str]) -> dict:
    args = ["--workflow", workflow, "--task", task, "--catalog", "${var.catalog}", "--landing-root", "${var.landing_root}"]
    for p in params:
        args += ["--param", f"{p}=${{var.{p}}}"]
    for u in upstream:
        args += ["--upstream-task", u]
    t = {"task_key": key}
    if deps:
        t["depends_on"] = [{"task_key": d} for d in deps]
    t.update({
        "job_cluster_key": "biis",
        "python_wheel_task": {"package_name": "biis_lakehouse", "entry_point": "biis-run", "parameters": args},
        "libraries": [{"whl": "../dist/*.whl"}] + ([{"pypi": {"package": PARAMIKO}}] if workflow == "ops" else []),
    })
    return t


def _email_var(value: str | None) -> list[str]:
    if value and value.startswith("$$WF_"):
        return ["${var.%s}" % var_name(value)]
    return ["${var.ehrp_notification_email}"] if value else []


def _job_cluster() -> list[dict]:
    return [{"job_cluster_key": "biis", "new_cluster": {
        "spark_version": "${var.spark_version}",
        "node_type_id": "${var.node_type_id}",
        "num_workers": "${var.num_workers}",
        "data_security_mode": "SINGLE_USER",
    }}]


def job_tasks(wf: Workflow) -> list[dict]:
    """XML chain with ops tasks wired in: ``<s>__pre`` -> ``<s>`` -> ``<s>__post``; Email tasks run via ``ops``."""
    commands = {(c.session, c.phase): c for c in SESSION_COMMANDS if c.workflow == wf.name}
    wf_params = [var_name(p) for p in wf.params]
    ops_params = wf_params + OPS_PARAMS
    tasks, prev, setters = [], None, []

    def add(key, workflow, task, params):
        nonlocal prev
        tasks.append(_wheel_task(key, workflow, task, params, list(setters), [prev] if prev else []))
        prev = key

    for name, ttype in wf.chain:
        if ttype == "Email":
            if EMAIL_TASKS[name][0] != wf.name:
                raise ValueError(f"{name} registered for {EMAIL_TASKS[name][0]}, found in {wf.name}")
            add(name, "ops", name, ops_params)
            continue
        if ttype != "Session":
            raise ValueError(f"{wf.name}: unsupported task type {ttype} for {name}")
        if (name, "pre") in commands:
            add(commands[(name, "pre")].task_key, "ops", commands[(name, "pre")].task_key, ops_params)
        add(name, wf.name, name, wf_params)
        if name in wf.var_setters:
            setters.append(name)
        if (name, "post") in commands:
            add(commands[(name, "post")].task_key, "ops", commands[(name, "post")].task_key, ops_params)
    return tasks


def workflow_job(wf: Workflow) -> dict:
    job = {
        "name": f"${{bundle.target}}-{wf.name}",
        "description": f"PowerCenter {wf.name} ({wf.schedule.get('SCHEDULETYPE', 'ONDEMAND')}); sessions in WORKFLOWLINK order.",
        "max_concurrent_runs": 1,
        "tags": {"powercenter_workflow": wf.name, "subject_area": "ehrp" if wf.name == EHRP_WF else "biis"},
        "job_clusters": _job_cluster(),
        "tasks": job_tasks(wf),
    }
    failure = _email_var(wf.failure_list)
    success = _email_var(wf.success_list) if wf.name == EHRP_WF else []
    notify = {}
    if success:
        notify["on_success"] = success
    if failure or success:
        notify["on_failure"] = list(failure or success)
    if notify:
        job["email_notifications"] = notify
    return job


def ehrp_daily_job(wf: Workflow) -> dict:
    s = wf.schedule
    if s.get("SCHEDULETYPE") != "RECURRING" or (s.get("DAYS"), s.get("HOURS"), s.get("MINUTES")) != ("1", "0", "0"):
        raise ValueError(f"unexpected {EHRP_WF} schedule {s}")
    hh, mm = s["STARTTIME"].split(":")
    sql = lambda key, deps: {  # noqa: E731
        **_wheel_task(key, "ehrp2biis_sql", key, [], [], deps)}
    tasks = [
        sql("preload", []),
        {"task_key": EHRP_WF, "depends_on": [{"task_key": "preload"}],
         "run_job_task": {"job_id": "${resources.jobs.%s.id}" % EHRP_WF}},
        sql("afterload", [EHRP_WF]),
        sql("actstage_load", ["afterload"]),
    ]
    return {
        "name": "${bundle.target}-ehrp2biis_daily",
        "description": f"ehrp2biis_preload -> {EHRP_WF} -> ehrp2biis_afterload -> actstage_load; "
                       f"PowerCenter schedule RECURRING every {s['DAYS']} day from {s['STARTDATE']} {s['STARTTIME']}.",
        "max_concurrent_runs": 1,
        "tags": {"powercenter_workflow": EHRP_WF, "subject_area": "ehrp"},
        "schedule": {"quartz_cron_expression": f"0 {int(mm)} {int(hh)} * * ?",
                     "timezone_id": "${var.schedule_timezone}",
                     "pause_status": "${var.ehrp_schedule_pause_status}"},
        "email_notifications": {"on_failure": ["${var.ehrp_notification_email}"]},
        "job_clusters": _job_cluster(),
        "tasks": tasks,
    }


def pay_period_job() -> dict:
    tasks = []
    for wf, deps in PAY_PERIOD_DEPENDS.items():
        t = {"task_key": wf}
        if deps:
            t["depends_on"] = [{"task_key": d} for d in deps]
        t["run_job_task"] = {"job_id": "${resources.jobs.%s.id}" % wf}
        tasks.append(t)
    return {
        "name": "${bundle.target}-biis_pay_period",
        "description": "Bi-weekly pay-period run (PLAN.md section 4.1). On demand, like the PowerCenter workflows.",
        "max_concurrent_runs": 1,
        "tags": {"subject_area": "biis"},
        "email_notifications": {"on_failure": ["${var.WF_CPM_EMAIL_LIST}"]},
        "tasks": tasks,
    }


def variables(wfs: dict[str, Workflow]) -> dict:
    used: dict[str, set[str]] = {}
    for wf in wfs.values():
        for p in wf.params:
            used.setdefault(p, set()).add(wf.name)
    out = {}
    for p in sorted(used, key=var_name):
        name = var_name(p)
        if p.startswith("$Param_"):
            default = f"<{name}>" if name not in ("Root_Directory", "ControlDir") else "/Volumes/biis/landing/files"
        elif name.endswith("EMAIL_LIST"):
            default = f"biis-{name.removeprefix('WF_').removesuffix('_EMAIL_LIST').lower().replace('_', '-')}@example.com"
        elif name in ("WF_SUBJECT", "WF_MESSAGE"):
            default = "0"
        else:
            default = ""
        out[name] = {"description": f"PowerCenter {p} ({', '.join(sorted(used[p]))}); set from the session "
                                    f"task values at run time when a session assigns it." if p.startswith("$$WF_")
                     else f"PowerCenter {p} ({', '.join(sorted(used[p]))}).", "default": default}
    return out


def render() -> dict[str, str]:
    wfs = load_workflows()
    files = {"variables.yml": {"variables": variables(wfs)}}
    for wf in wfs.values():
        files[f"{wf.name}.job.yml"] = {"resources": {"jobs": {wf.name: workflow_job(wf)}}}
    files["ehrp2biis_daily.job.yml"] = {"resources": {"jobs": {"ehrp2biis_daily": ehrp_daily_job(wfs[EHRP_WF])}}}
    files["biis_pay_period.job.yml"] = {"resources": {"jobs": {"biis_pay_period": pay_period_job()}}}
    return {k: HEADER + yaml.safe_dump(v, sort_keys=False, width=1000) for k, v in files.items()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for name, text in render().items():
        path = HERE / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print("stale: " + ", ".join(stale) + " (run python resources/generate.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
